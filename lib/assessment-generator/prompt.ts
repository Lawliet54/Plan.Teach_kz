import type { AssessmentGeneratorRequest } from "@/lib/assessment-generator/types";

export function buildAssessmentPrompt(request: AssessmentGeneratorRequest) {
  const assessmentLabel =
    request.type === "bjb"
      ? "БЖБ — бөлім бойынша жиынтық бағалау"
      : "ТЖБ — тоқсан бойынша жиынтық бағалау";

  const objectives = request.learningObjectives
    .map((objective) => `- ${objective}`)
    .join("\n");

  return `
Сіз Қазақстан мектептеріне арналған физика пәні бойынша кәсіби критериалды бағалау материалдарын құрастыратын әдіскерсіз.

Құжат түрі:
${assessmentLabel}

Параметрлер:
- Сынып: ${request.grade}
- Тоқсан: ${request.term}
- Негізгі бөлім немесе тақырыптар: ${request.section}
- Орындау уақыты: ${request.durationMinutes} минут
- Тапсырма саны: ${request.taskCount}
- Жалпы балл: ${request.totalPoints}

Оқу мақсаттары:
${objectives || "- Оқу мақсаттарын бөлім мазмұнына сәйкес өзіңіз анықтаңыз"}

Қосымша талаптар:
${request.additionalRequirements || "Қосымша талап жоқ."}

МІНДЕТТІ ЕРЕЖЕЛЕР:
1. Барлық мәтінді сауатты қазақ тілінде жазыңыз.
2. Тек физика пәніне қатысты мазмұн құрастырыңыз.
3. Оқу мақсаттары, бағалау критерийлері, тапсырмалар, жауаптар және дескрипторлар бір-біріне дәл сәйкес болуы керек.
4. Бөлімге қатысы жоқ тапсырма қоспаңыз.
5. Ұлттық құндылықты міндетті түрде қоспаңыз. Бейтарап өмірлік және практикалық мысалдар қолданыңыз.
6. Суретсіз орындалмайтын тапсырма жасамаңыз. Қажет болса диаграмманы немесе жағдайды толық мәтінмен сипаттаңыз.
7. Есептердің сандық мәндері нақты шешілетіндей болсын.
8. Әр тапсырманың баллы оның дескрипторлары баллдарының қосындысына тең болсын.
9. Барлық тапсырмалардың жалпы баллы дәл ${request.totalPoints} болсын.
10. Әр тапсырма үшін нақты жауап жазыңыз.
11. Рубрикада төмен, орташа және жоғары деңгей сипаттамаларын беріңіз.
12. qualityChecks ішінде мазмұнның оқу мақсаттарына сәйкестігін тексергеніңізді жазыңыз.

БЖБ үшін:
- specification массиві бос болуы керек.
- Бір бөлімге арналған ықшам құжат жасаңыз.

ТЖБ үшін:
- specification массивін міндетті түрде толтырыңыз.
- Әр бөлім бойынша оқу мақсаттарын, ойлау дағдыларын, тапсырма санын, тапсырма нөмірлерін, тапсырма түрлерін, уақытты және баллды көрсетіңіз.
- Тапсырма түрлерінде КТБ, ҚЖ немесе ТЖ белгілеулерін қолданыңыз.

JSON Schema талабына сәйкес тек құрылымды JSON жауап қайтарыңыз.
`;
}
