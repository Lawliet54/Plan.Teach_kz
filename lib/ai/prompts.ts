/**
 * Generate a fallback topic tutor response
 */
export function generateLocalTopicTutorResponse(
  topicTitle: string,
  userMessage: string,
  level: StudentLevel
): string {
  const baseResponse = kazakhFallbackResponses.topicExplainationSimple(topicTitle);

  if (level === "beginner") {
    return `${baseResponse}\n\nСіздің сұрағыңыз: "${userMessage}"\n\nОңай елді істегідей ойлап еңбеңіз!`;
  }

  if (level === "intermediate") {
    return `${baseResponse}\n\nОйлау-ойлантарыңыз: "${userMessage}" деген сұрағы жөнінде?`;
  }

  return `${baseResponse}\n\nТеориялық талқылау: "${userMessage}"`;
}

