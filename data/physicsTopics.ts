export type Grade = 7 | 8 | 9 | 10 | 11;

export type TopicLevel = "basic" | "medium" | "advanced";

export type TaskType =
  | "test"
  | "fill-blank"
  | "matching"
  | "simulation"
  | "numeric"
  | "project";

export type TopicLevelContent = {
  level: TopicLevel;
  label: string;
  shortGoal: string;
  intro?: string;
  theory: string | string[];
  simpleExplanation: string;
  keyConcepts?: {
    term: string;
    definition: string;
  }[];
  formula?:
    | string
    | {
        expression: string;
        explanation: string;
        symbols: {
          symbol: string;
          meaning: string;
          unit?: string;
        }[];
      };
  units?: {
    name: string;
    symbol: string;
    explanation: string;
  }[];
  measurementTools?: {
    name: string;
    use: string;
  }[];
  realLifeExamples?: string[];
  workedExample?: {
    title: string;
    problem: string;
    given: string[];
    solutionSteps: string[];
    answer: string;
  };
  commonMistakes?: {
    mistake: string;
    correction: string;
  }[];
  remember?: string[];
  checkQuestions?: string[];
  keyPoints?: string[];
  example?: string;
  recommendedTasks: TaskType[];
};

export type PhysicsTopic = {
  id: string;
  grade: Grade;
  slug: string;
  title: string;
  unit: string;
  description: string;
  levels: Record<TopicLevel, TopicLevelContent>;
};

export const levelLabels: Record<TopicLevel, string> = {
  basic: "Базалық",
  medium: "Орташа",
  advanced: "Күрделі",
};

export function getFormulaExpression(
  formula: TopicLevelContent["formula"]
): string | null {
  if (!formula) return null;
  if (typeof formula === "string") return formula;
  return formula.expression;
}

export function getContentRememberItems(content: TopicLevelContent): string[] {
  return content.remember ?? content.keyPoints ?? [];
}

export function getContentExampleText(content: TopicLevelContent): string {
  if (content.workedExample) {
    return content.workedExample.answer;
  }

  return content.example ?? content.shortGoal;
}

