export function getTopicsByGrade(grade: Grade): PhysicsTopic[] {
  return physicsTopics.filter((topic) => topic.grade === grade);
}

export function getTopicBySlug(
  grade: Grade,
  slug: string
): PhysicsTopic | undefined {
  return physicsTopics.find(
    (topic) => topic.grade === grade && topic.slug === slug
  );
}

export function getLevelContent(topic: PhysicsTopic, level: TopicLevel) {
  return topic.levels[level];
}

export function isValidGrade(value: string): value is `${Grade}` {
  return ["7", "8", "9", "10", "11"].includes(value);
}

